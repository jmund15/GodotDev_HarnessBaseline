"""Generates .claude/plans/harness-v2.inventory.md from classes.json, analysis.json, the transcript scan and the spike files."""
import json
import os
import re
import subprocess
import sys
from collections import Counter, defaultdict
from datetime import datetime, timezone

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import common
import sec_transcripts

OUT = common.WT + "/.claude/plans/harness-v2.inventory.md"
CLS = json.load(open(common.SCR + "/classes.json"))
AN = json.load(open(common.SCR + "/analysis.json"))
KEYS = ["pp", "mm_main", "mm_r24"]
NAMES = {"pp": "PushinPotions `origin/main`", "mm_main": "MaddManager `main`", "mm_r24": "MaddManager `r24-int`"}
ORDER = ["shared", "pp-local", "mm-local", "delete", "bench-moved"]


def sha(key):
    t = common.TARGETS[key]
    return common.git(t["repo"], "rev-parse", t["ref"]).strip()


def rp(p):
    return p[len(".claude/"):]


def read(name):
    return open(common.SCR + "/" + name, encoding="utf-8", errors="replace").read()


def sec_header():
    ver = subprocess.run(["claude", "--version"], capture_output=True, text=True).stdout.strip()
    L = ["# Harness v2 S4 inventory", "",
         "Generated by `.claude/scratch/v2_s4/` (`classify.py`, `analyze.py`, `scan_transcripts.py`, `sec_transcripts.py`, `build_inventory.py`; gitignored, regenerated from the refs below). "
         f"Plan: `.claude/plans/harness-v2.md` §M2 S4 and S4b. Generated {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%MZ')}.", "",
         f"**Client:** `claude --version` prints `{ver}`. Every crafted call, plugin command and `Agent` call below ran on it.", "",
         "| Target | Ref | Commit | Tracked `.claude/` paths |", "|---|---|---|---|"]
    for k in KEYS:
        t = common.TARGETS[k]
        n = len(common.file_list(k))
        L.append(f"| {NAMES[k]} | `{t['branch']}` | `{sha(k)[:12]}` (pinned: the branch moved while this ran) | {n:,} |")
    L += ["", "Paths are read with `git ls-tree -r --name-only <ref> -- .claude` and contents with `git cat-file --batch` (MaddManager is read-only). `git ls-files .claude | wc -l` at a ref equals the `ls-tree` count above.", ""]
    return "\n".join(L)


def sec_check():
    L = ["## Check results", "", "Every tracked `.claude/` path appears exactly once in §Appendix A of its repo and branch. The class counts sum to the tracked count:", "",
         "| Target | Tracked | shared | local | delete | bench-moved | Sum | Sum = tracked | Paths unique | Kept, unplaced (listed in §Unplaced files) |", "|---|---|---|---|---|---|---|---|---|---|"]
    for k in KEYS:
        files = common.file_list(k)
        res = CLS[k]
        c = Counter(v["cls"] for v in res.values())
        loc = c.get("pp-local", 0) + c.get("mm-local", 0)
        s = c["shared"] + loc + c["delete"] + c["bench-moved"]
        un = sum(1 for v in res.values() if v["conf"] == "unplaced")
        L.append(f"| {NAMES[k]} | {len(files):,} | {c['shared']:,} | {loc:,} | {c['delete']:,} | {c['bench-moved']:,} | {s:,} | {'yes' if s == len(files) else 'NO'} | {'yes' if len(set(files)) == len(files) == len(res) else 'NO'} | {un} |")
    for k in KEYS:
        refd = {h["deleted"] for h in AN["importers"][k]["hits"]}
        nd = AN["importers"][k]["deleted"]
        L.append(f"- {NAMES[k]}: {nd:,} deleted or moved files; {len(refd):,} have at least one kept referrer (listed in §Appendix B); {nd - len(refd):,} have none.")
    L += ["", "**Every deleted file's kept importers** are in §Importers of deleted files and §Appendix B, one entry per deleted file. Behaviour dependencies (an import, a spawn, a hook wiring) are listed with their line. Prose citations in `.md` files are listed per file with a count.", ""]
    return "\n".join(L)


def sec_counts():
    L = ["## Per-class counts", "", "`conf` shows how a path got its class: **named** (a V row or T-part names the file or its directory), **family** (a V row names the family, not the file), **derived** (its test, its fixture, or a helper a kept file imports or names), **lock** (only the repo's lock row decides; used for doctrine under V13), **unplaced** (no row reaches it; kept by its lock row and listed).", ""]
    for k in KEYS:
        res = CLS[k]
        cc = defaultdict(Counter)
        for v in res.values():
            cc[v["cls"]][v["conf"]] += 1
        L += [f"### {NAMES[k]}", "", "| class | total | named | family | derived | lock | unplaced |", "|---|---|---|---|---|---|---|"]
        for c in ORDER:
            if c in cc:
                x = cc[c]
                L.append(f"| {c} | {sum(x.values()):,} | {x['named']} | {x['family']} | {x['derived']} | {x['lock']} | {x['unplaced']} |")
        top = Counter()
        for p, v in res.items():
            top[(rp(p).split("/")[0] if "/" in rp(p) else "(root)", v["cls"])] += 1
        dirs = sorted({d for d, _ in top})
        L += ["", "By top-level directory:", "", "| dir | " + " | ".join(c for c in ORDER if c in cc) + " |", "|---|" + "---|" * len([c for c in ORDER if c in cc])]
        for d in dirs:
            L.append(f"| {d} | " + " | ".join(str(top.get((d, c), 0)) for c in ORDER if c in cc) + " |")
        L.append("")
    L += ["Reading the classes: a **delete** in MaddManager is a file MaddManager drops (it holds a PushinPotions-local Godot file through a layer, or a v1 machine v2 removes). **shared** is a file both repos hold byte-identical after v2 (T7); a shared file that is `forked` in a repo's lock needs reconciling at S6b (count in §Per-slice file counts). The script keeps every kept helper it finds a kept file importing or naming (`derived`); those follow v1's imports, so S5 and S6b rewrites may drop more.", ""]
    return "\n".join(L)


