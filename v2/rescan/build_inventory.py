def slice_counts():
    L = ["## Per-slice file counts for M2–M4", "", "Counts of tracked `.claude/` files the classification assigns to each slice's work, per repo at the ref. They are file counts, not effort. S5, S6a, S6b and S7 write the shared repo's `v2` branch once; S8 and S9 apply it to a repo; S10 and S11 are sweeps.", ""]
    fl = re.compile(r"(dangerous_shell_guard|git_guardrails|_peer_loss|kill_guard|_regenerable_clone|_git_run|_git_commit|_shell_lex|_shell_writes|sidecar_workdir_guard|agy_hook_bridge|transcript_backup|index_commit|reap\.py)")
    DOC = ("commands/", "skills/", "rules/", "reference/", "guards/", "agents/", "output-styles/")
    for k in ("pp", "mm_main", "mm_r24"):
        res = CLS[k]
        t = Counter()
        for p, v in res.items():
            r = rp(p)
            sub = v["note"].replace("test of ", "") if v["note"].startswith("test of ") else r
            floor = bool(fl.search(sub))
            if v["cls"] == "shared":
                if r.startswith("tests/"):
                    t["S5 floor tests" if floor else "S6b tests of shared mechanisms"] += 1
                elif floor:
                    t["S5 floor modules"] += 1
                elif r.startswith(DOC):
                    t["S6a shared doctrine to rewrite"] += 1
                else:
                    t["S6b shared mechanisms and data"] += 1
            elif v["cls"] in ("delete", "bench-moved"):
                if r.startswith(DOC):
                    t["S6a doctrine deleted (carried/dropped table)"] += 1
                elif r.startswith("tests/"):
                    t["S6b/S8/S9 tests deleted with their subject"] += 1
                else:
                    t["S8/S9 non-doctrine, non-test files deleted at cutover"] += 1
            else:
                if r.startswith("auto-memory/"):
                    t["S10 memory files (archive pass over the whole set)"] += 1
                elif r.startswith("plans/"):
                    t["S10 plan files (archive pass over the whole set)"] += 1
                else:
                    t["local files kept (S12 for MaddManager's UI tooling; S9 edits PushinPotions-local callers)"] += 1
        imp = AN["importers"][k]["hits"]
        cuts = Counter(h["cut"] for h in imp if h["kind"] in ("import", "spawn", "wired") and not rp(h["kept"]).startswith(("plans/", "auto-memory/", "tests/fixtures", "tests/agent_fixtures")))
        shared = sum(1 for v in res.values() if v["cls"] == "shared")
        dele = sum(1 for v in res.values() if v["cls"] in ("delete", "bench-moved"))
        forked = 0
        lk = common.lock(k)["files"]
        for p, v in res.items():
            if v["cls"] == "shared" and lk.get(p, {}).get("status") == "forked":
                forked += 1
        L += [f"### {NAMES[k]}", "", "| Slice work | files |", "|---|---|"]
        for a, b in sorted(t.items()):
            L.append(f"| {a} | {b:,} |")
        L.append(f"| S6b/S8/S9 kept-caller cuts (behaviour references in kept non-test, non-fixture files): " + ", ".join(f"{a} {b}" for a, b in cuts.most_common()) + " | " + f"{sum(cuts.values()):,} |")
        L += ["", f"Cutover commit size: {dele:,} files removed, {shared:,} shared files written or kept byte-identical by `harness_sync.py pull`, {forked} of those are `forked` in the repo's lock today (their local bytes differ from the shared file and S8/S9 reconcile each).", ""]
    L += ["S7 adds one workflow and one pytest config to the shared repo; S11 changes one setting; S12 is MaddManager-owned (its `mm-local` files above).", ""]
    return "\n".join(L)


def appendix_a():
    L = ["## Appendix A: every tracked `.claude/` path, once, with its class", "", "One line per path, grouped by repo and branch, class, V/T row and how it was placed (`named`, `family`, `derived`, `lock`, `unplaced`). Repo-relative paths.", ""]
    for k in KEYS:
        res = CLS[k]
        L += [f"### A.{KEYS.index(k) + 1} {NAMES[k]} ({len(res):,} paths)", ""]
        groups = defaultdict(list)
        for p, v in res.items():
            groups[(ORDER.index(v["cls"]), v["cls"], v["row"], v["conf"])].append(p)
        for key in sorted(groups):
            _, cl, row, conf = key
            ps = sorted(groups[key])
            L += [f"#### {NAMES[k]}: {cl}, row {row}, {conf} ({len(ps):,})", "", "```"]
            L += ps
            L += ["```", ""]
    return "\n".join(L)


def appendix_b():
    L = ["## Appendix B: kept referrers of each deleted file", "", "One entry per deleted or moved file that a kept file references: `kept path@first line (kinds)`. Plans and memory files are shown as a count. For `r24-int` only the entries that differ from `main` are listed; every other pair is identical to `main`'s (script-verified count given).", ""]
    base = {}
    for k in KEYS:
        imp = AN["importers"][k]["hits"]
        by = defaultdict(lambda: defaultdict(lambda: [10 ** 9, set(), 0]))
        for h in imp:
            e = by[h["deleted"]][h["kept"]]
            e[0] = min(e[0], h["line"])
            e[1].add(h["kind"])
            e[2] += 1
        ent = {}
        for d, ks in by.items():
            parts = []
            pm = 0
            for kept, (ln, kinds, n) in sorted(ks.items()):
                if rp(kept).startswith(("plans/", "auto-memory/")):
                    pm += 1
                else:
                    parts.append(f"`{rp(kept)}`@{ln} ({'/'.join(sorted(kinds))}{'×' + str(n) if n > 1 else ''})")
            ent[d] = "; ".join(parts) + (f"; +{pm} plan or memory file(s)" if pm else "")
        base[k] = ent
    for k in ("pp", "mm_main"):
        L += [f"### B.{KEYS.index(k) + 1} {NAMES[k]}", ""]
        for d in sorted(base[k]):
            L.append(f"- `{rp(d)}` ← {base[k][d]}")
        L.append("")
    same = sum(1 for d in base["mm_r24"] if base["mm_main"].get(d) == base["mm_r24"][d])
    L += [f"### B.3 {NAMES['mm_r24']}", "", f"{len(base['mm_r24'])} deleted files with kept referrers; {same} entries equal `main`'s. Entries that differ or are new:", ""]
    for d in sorted(base["mm_r24"]):
        if base["mm_main"].get(d) != base["mm_r24"][d]:
            L.append(f"- `{rp(d)}` ← {base['mm_r24'][d]}")
    L.append("")
    return "\n".join(L)


