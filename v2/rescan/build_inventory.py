def importer_tables():
    L = ["## Importers of deleted files", "",
         "A kept file is any file the classification does not delete or move. Method: Python imports by `ast` (a name that is one deleted module's stem; a stem shared by a kept and a deleted file is skipped and listed below); JavaScript `require`, `import` and `from` specifiers by stem; every other reference by literal match of a deleted file's repo-relative path, or of its basename when the basename is at least 8 characters and unique among the tracked files. "
         "Kinds: **import** (a Python or JavaScript import of a deleted module: a behaviour dependency), **spawn** (a code line or hook command that runs the deleted file: a behaviour dependency), **wired** (a `settings.json` hook entry that runs it: a behaviour dependency), **path-string** (a code or data line that names the path without running it on that line), **citation** (prose in an `.md` file). "
         "`tests/fixtures/**` files are data and counted apart; `plans/` and `auto-memory/` files are archive material and counted per file (S10's sweep). Limits: a command name cited as `/name` is not matched; a path built at run time is not seen (the plan's own caveat for S4).", ""]
    for k in KEYS:
        imp = AN["importers"][k]
        hits = imp["hits"]
        kinds = Counter(h["kind"] for h in hits)

        def bucket(h):
            r = rp(h["kept"])
            return "plans/memory" if r.startswith(("plans/", "auto-memory/")) else "fixture data" if r.startswith(("tests/fixtures", "tests/agent_fixtures")) else "tests" if r.startswith("tests/") else "other kept"
        pairs = defaultdict(set)
        for h in hits:
            pairs[(bucket(h), h["kept"], h["deleted"])].add(h["kind"])
        L += [f"### {NAMES[k]}", "", f"{imp['deleted']:,} deleted or moved files; {len(hits):,} references from kept files: " + ", ".join(f"{a} {b:,}" for a, b in kinds.most_common()) + ".", ""]
        cnt = Counter(b for (b, _, _) in pairs)
        L.append("Distinct (kept file, deleted file) pairs: " + ", ".join(f"{a} {b:,}" for a, b in cnt.most_common()) + ".")
        beh = [h for h in hits if h["kind"] in ("import", "spawn", "wired") and bucket(h) in ("other kept", "tests")]
        by = Counter(h["cut"] for h in beh)
        L += ["", "Behaviour dependencies (import, spawn, wired) in kept non-fixture files, by the slice that cuts them: " + ", ".join(f"{a} {b}" for a, b in by.most_common()) + ".", ""]
        if imp["ambiguous_stems"]:
            L.append("Stems shared by a kept and a deleted module, not matched by import: " + ", ".join(f"`{s}`" for s in imp["ambiguous_stems"]) + ".")
            L.append("")
        # behaviour list for non-test kept files only
        nontest = [h for h in beh if bucket(h) == "other kept"]
        grp = defaultdict(list)
        for h in nontest:
            grp[h["cut"]].append(h)
        L += [f"#### Behaviour dependencies of kept non-test files ({len(nontest)})", ""]
        for cut, hs in sorted(grp.items()):
            L += [f"**{cut}** ({len(hs)})", ""]
            byk = defaultdict(list)
            for h in hs:
                byk[h["kept"]].append(h)
            for kept, hh in sorted(byk.items()):
                items = "; ".join(f"{h['line']} {h['kind']} → `{rp(h['deleted'])}`" for h in sorted(hh, key=lambda x: (x["line"], x["deleted"]))[:14])
                more = f" (+{len(hh) - 14} more)" if len(hh) > 14 else ""
                L.append(f"- `{rp(kept)}`: {items}{more}")
            L.append("")
        L.append("")
    return "\n".join(L)


