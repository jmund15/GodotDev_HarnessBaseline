    gone = sorted(set(mm) - set(r24))
    L += ["", f"### {NAMES['mm_r24']} ({len(r24)})", "", f"Same as `main` except {len(extra)} added and {len(gone)} removed: " + (", ".join(f"`{rp(p)}`" for p in extra) or "none added") + "; removed: " + (", ".join(f"`{rp(p)}`" for p in gone) or "none") + ".", ""]
    return "\n".join(L)


