def sec_unplaced():
    L = ["## Unplaced files (kept; the owner places them)", "", "No V row or named part reaches these files and no kept file names them. The script keeps each by its lock row. A referrer count (kept, deleted or moved) is a hint: a hook or tool with no kept referrer is a delete candidate.", ""]
    pp = {p: v for p, v in CLS["pp"].items() if v["conf"] == "unplaced"}
    L += [f"### {NAMES['pp']} ({len(pp)})", "", "| path | kept as | why unplaced |", "|---|---|---|"]
    for p in sorted(pp):
        L.append(f"| `{rp(p)}` | {pp[p]['cls']} | {pp[p]['note'].replace('|', '/')[:150]} |")
    mm = {p: v for p, v in CLS["mm_main"].items() if v["conf"] == "unplaced"}
    L += ["", f"### {NAMES['mm_main']} ({len(mm)})", "", "| path | kept as | why unplaced |", "|---|---|---|"]
    for p in sorted(mm):
        L.append(f"| `{rp(p)}` | {mm[p]['cls']} | {mm[p]['note'].replace('|', '/')[:150]} |")
    r24 = {p: v for p, v in CLS["mm_r24"].items() if v["conf"] == "unplaced"}
