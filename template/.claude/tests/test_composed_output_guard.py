"""Proof for hooks/composed_output_guard.py: a Write/Edit on a composed file is denied with the
input to edit instead, because `baseline_sync.py compose` regenerates the file and silently
drops a direct edit (settings.json, 2026-09-22). Inputs and ordinary files pass.

    python3 .claude/tests/test_composed_output_guard.py
"""
import json
import os
import subprocess
import sys

HOOKS = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "hooks")
sys.path.insert(0, HOOKS)
import composed_output_guard as guard  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(HOOKS))
FAILURES = []


def edit(rel, tool="Edit"):
    path = os.path.join(ROOT, *rel.split("/"))
    tool_input = {"file_path": path, "old_string": "a", "new_string": "b"} if tool == "Edit" \
        else {"file_path": path, "content": "{}"}
    return {"tool_name": tool, "tool_input": tool_input, "session_id": "composed-proof"}


def check(label, ok, detail=""):
    print("%-4s %s" % ("ok" if ok else "FAIL", label))
    if not ok:
        FAILURES.append("%s :: %s" % (label, str(detail)[:300]))


for rel, tool, home in (
    (".claude/settings.json", "Edit", "rules/harness_tooling.md"),
    (".claude/settings.json", "Write", "rules/harness_tooling.md"),
    (".claude/reference/memory_domains.md", "Edit", "reference/memory_domains.base.md header"),
):
    got = guard.process(edit(rel, tool)) or {}
    block = got.get("block", "")
    check("%s %s is blocked" % (tool, rel), "block" in got, got)
    check("%s %s block names an input and compose" % (tool, rel),
          "compose" in block and ".base." in block, got)
    check("%s %s block cites its home and names the next step" % (tool, rel),
          home in block and "then run `python3 .claude/tools/baseline_sync.py compose`" in block, got)

for rel in (".claude/settings.project.json", ".claude/settings.base.json", ".claude/settings.local.json",
            ".claude/reference/memory_domains.base.md", ".claude/hooks/x.py"):
    check("Edit %s passes" % rel, not guard.process(edit(rel)), rel)
check("a worktree's composed settings.json is blocked too",
      "block" in (guard.process(edit(".claude/worktrees/wt/.claude/settings.json")) or {}))
check("a Bash payload is ignored", not guard.process({"tool_name": "Bash", "tool_input": {"command": "x"}}))
check("the cheap name prefilter lists exactly the composed files baseline_sync owns",
      guard.COMPOSED_NAMES == {os.path.basename(k) for k in guard._composed_inputs()},
      getattr(guard, "COMPOSED_NAMES", None))

dispatcher = os.path.join(HOOKS, "pre_edit_dispatch.py")
for rel, tool, home in (
    (".claude/settings.json", "Edit", "rules/harness_tooling.md"),
    (".claude/settings.json", "Write", "rules/harness_tooling.md"),
    (".claude/reference/memory_domains.md", "Edit", "reference/memory_domains.base.md header"),
):
    r = subprocess.run([sys.executable, dispatcher], input=json.dumps(edit(rel, tool)),
                       capture_output=True, text=True, timeout=60)
    check("the live dispatcher blocks %s %s on stderr with cite and next step" % (tool, rel),
          r.returncode == 2 and home in r.stderr
          and "then run `python3 .claude/tools/baseline_sync.py compose`" in r.stderr
          and not r.stdout, r.stderr or r.stdout)

# A generated REGION (`GENERATED by <tool> from <src> - do not edit` .. `END GENERATED by <tool>`): the
# generator overwrites, or refuses as HAND-EDITED, any change inside it (score_cell.js, 2026-10-01). The block names
# the source and the regen command; text outside the region, and a file with no region, pass.
import tempfile  # noqa: E402
with tempfile.TemporaryDirectory() as raw:
    pkg = os.path.join(raw, "pkg")
    os.makedirs(os.path.join(pkg, "scoring"))
    open(os.path.join(pkg, "gen_views.py"), "w").write("# generator\n")
    gen = os.path.join(pkg, "scoring", "view.js")
    open(gen, "w", newline="\n").write("const hand = 1\n// GENERATED by gen_views.py from core/table.json - do not edit. sha256="
                                         + "0" * 64 + "\nconst inside = 2\n// END GENERATED by gen_views.py\nconst after = 3\n")
    plain = os.path.join(pkg, "plain.js")
    open(plain, "w", newline="\n").write("const inside = 2\n")
    def ed(path, old, new="x", tool="Edit"):
        ti = {"file_path": path, "old_string": old, "new_string": new} if tool == "Edit" else {"file_path": path, "content": new}
        return {"tool_name": tool, "tool_input": ti, "session_id": "composed-proof"}
    got = guard.process(ed(gen, "const inside = 2")) or {}
    b = got.get("block", "")
    check("Edit inside a generated region is blocked", "block" in got, got)
    check("the block names the source, the generator's own path and the regen command",
          "core/table.json" in b.replace("\\", "/") and "gen_views.py" in b and "then run" in b, b)
    check("Edit outside the region passes", not guard.process(ed(gen, "const after = 3")))
    check("Edit that starts above the region and runs into its body is blocked",
          "block" in (guard.process(ed(gen, "const hand = 1\n// GENERATED by gen_views.py from core/table.json")) or {}))
    check("Edit of the region's marker line alone is blocked",
          "block" in (guard.process(ed(gen, "// GENERATED by gen_views.py from core/table.json - do not edit")) or {}))
    check("Edit that ends just before the region passes", not guard.process(ed(gen, "const hand = 1\n")))
    check("Edit of a file with no region passes", not guard.process(ed(plain, "const inside = 2")))
    multi = os.path.join(pkg, "scoring", "multi.sh")
    open(multi, "w", newline="\n").write("# GENERATED by gen_views.py from core/roots.py and core/table.json - do not edit. x\n"
                                          "X=1\n# END GENERATED by gen_views.py\n")
    b = (guard.process(ed(multi, "X=1")) or {}).get("block", "").replace("\\", "/")
    check("a multi-source marker is named whole, relative to the generator's directory, never with the directory on its first path only",
          "core/roots.py and core/table.json (relative to " in b and "/core/roots.py and" not in b, b)
    twice = os.path.join(pkg, "scoring", "twice.js")
    open(twice, "w", newline="\n").write(
        "const x = 2\n// GENERATED by gen_views.py from core/table.json - do not edit. sha256=" + "0" * 64
        + "\nconst x = 2\n// END GENERATED by gen_views.py\n")
    replace_all = ed(twice, "const x = 2")
    replace_all["tool_input"]["replace_all"] = True
    check("a replace_all Edit whose text also appears inside a region is blocked",
          "block" in (guard.process(replace_all) or {}))
    whole = open(gen).read()
    check("Write that changes the region is blocked",
          "block" in (guard.process(ed(gen, None, whole.replace("inside = 2", "inside = 9"), "Write")) or {}))
    check("Write that changes only the region marker's recorded sha256 is blocked",
          "block" in (guard.process(ed(gen, None, whole.replace("0" * 64, "1" * 64), "Write")) or {}))
    check("Write that keeps the region byte-identical passes",
          not guard.process(ed(gen, None, whole.replace("after = 3", "after = 4"), "Write")))
    r = subprocess.run([sys.executable, dispatcher], input=json.dumps(ed(gen, "const inside = 2")),
                       capture_output=True, text=True, timeout=60)
    check("the live dispatcher blocks a generated-region edit on stderr", r.returncode == 2 and "core/table.json" in r.stderr.replace("\\", "/"),
          r.stderr or r.stdout)

# The user-level ~/.claude/settings.json is not the project's composed file: compose never writes it, so a
# block there names a rule the user was not breaking (2026-10-10). The project's own file stays blocked.
with tempfile.TemporaryDirectory() as home:
    saved = {k: os.environ.get(k) for k in ("HOME", "USERPROFILE")}
    os.environ["HOME"] = os.environ["USERPROFILE"] = home
    try:
        user_settings = os.path.join(home, ".claude", "settings.json")
        check("Edit of the user-level ~/.claude/settings.json passes",
              not guard.process(ed(user_settings, "a")), guard.process(ed(user_settings, "a")))
        check("Write of the user-level ~/.claude/settings.json passes",
              not guard.process(ed(user_settings, None, "{}", "Write")))
        check("the project's own settings.json is still blocked while HOME differs",
              "block" in (guard.process(edit(".claude/settings.json")) or {}))
    finally:
        for k, v in saved.items():
            if v is None:
                os.environ.pop(k, None)
            else:
                os.environ[k] = v

print("\n%d failure(s)" % len(FAILURES) if FAILURES else "\nall ok")
for f in FAILURES:
    print("  " + f)
sys.exit(1 if FAILURES else 0)
