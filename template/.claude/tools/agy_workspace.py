#!/usr/bin/env python3
"""Write the `.agents/` workspace that gives the Antigravity CLI this project's harness: its CLAUDE layers and memory index
as always-on rules, its path rules and skills as on-demand pointers, its shell-call hook (the loss floor) through
`hooks/agy_hook_bridge.py`, and its read-only MCP servers.

    agy_workspace.py write --root <checkout>     regenerate <checkout>/.agents; prints `wrote N` or `skipped: <why>`

Every file points at the checkout's own `.claude/` source, so nothing is copied but skill descriptions and the
MCP launch lines. `.agents/` is gitignored and regenerated by the antigravity launcher before each run, so it never
drifts or dirties a peer's tree. A root that is not a checkout of this project gets nothing.
"""
import argparse
import glob
import json
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "hooks"))
from _hook_state import replace_path  # noqa: E402

MARK = "<!-- generated by .claude/tools/agy_workspace.py; edit the .claude source instead -->"
LAYERS = ("CLAUDE.md", "CLAUDE.core.md")
# Claude Code loads the memory index into every session beside the layers (CLAUDE.core.md §Memory).
MEMORY_INDEX = ".claude/auto-memory/MEMORY.md"
# The read-only MCP servers a workspace wires; tools/agy_seat.py grants a read kind exactly these. semantic-search
# comes from its installed plugin, the rest from the project's .mcp.json. A server that edits the project stays out.
READ_ONLY_SERVERS = ("semantic-search", "git")
DEFAULT_HOOK_TIMEOUT = 60  # Claude Code's own default for a command hook that sets none


def _frontmatter(text):
    m = re.match(r"---\r?\n(.*?)\r?\n---\r?\n", text, re.S)
    return m.group(1) if m else ""


def _description(front):
    m = re.search(r"^description:\s*(>-?|\|-?)?\s*\n?((?:[ \t]+.*\n?)+|.*)$", front, re.M)
    if not m:
        return ""
    return " ".join(line.strip() for line in m.group(2).splitlines() if line.strip()).strip("'\"")


def _paths(front):
    block = re.search(r"^paths:\s*\n((?:\s+-\s*.*\n?)+)", front, re.M)
    return [p.strip().strip("'\"") for p in re.findall(r"-\s*(.+)", block.group(1))] if block else []


def rules(root):
    """{relative path: content} for the rule files: one always-on file per CLAUDE layer (agy truncates a rule past
    24 KB, so the layers never share one) and one model-decision pointer per path rule."""
    out = {}
    for layer in LAYERS:
        if os.path.isfile(os.path.join(root, ".claude", layer)):
            slug = layer[:-3].replace(".", "_").lower()
            out[f"rules/{slug}.md"] = ("---\ntrigger: always_on\ndescription: project guidelines ({layer})\n---\n"
                                       f"{MARK}\n@[{layer}](../../.claude/{layer})\n")
    if os.path.isfile(os.path.join(root, MEMORY_INDEX)):
        out["rules/memory_index.md"] = ("---\ntrigger: always_on\ndescription: project memory index\n---\n"
                                        f"{MARK}\n@[MEMORY.md](../../{MEMORY_INDEX})\n")
    for path in sorted(glob.glob(os.path.join(root, ".claude", "rules", "*.md"))):
        name = os.path.basename(path)[:-3]
        globs = _paths(_frontmatter(open(path, encoding="utf-8").read()))
        if not globs:
            continue
        out[f"rules/path_{name}.md"] = (
            f"---\ntrigger: model_decision\ndescription: Read .claude/rules/{name}.md in full before reading or editing "
            f"files matching {', '.join(globs)}.\n---\n{MARK}\nRead `.claude/rules/{name}.md` in full and follow it.\n")
    return out


def skills(root):
    """{relative path: content}: one stub per model-invocable skill, carrying its description and pointing at it."""
    out = {}
    for path in sorted(glob.glob(os.path.join(root, ".claude", "skills", "*", "SKILL.md"))):
        folder = os.path.basename(os.path.dirname(path))
        front = _frontmatter(open(path, encoding="utf-8").read())
        if re.search(r"^disable-model-invocation:\s*true", front, re.M):
            continue
        desc = _description(front)
        if not desc:
            continue
        name = folder.replace("_", "-").lower()
        out[f"skills/{name}/SKILL.md"] = (
            f"---\nname: {name}\ndescription: {json.dumps(desc)}\n---\n{MARK}\n"
            f"Read `.claude/skills/{folder}/SKILL.md` in full and follow it. Paths it names are relative to the "
            f"repository root; read a reference file only when a step it governs comes up.\n")
    return out


def _bridge_timeout(root):
    """Seconds agy waits for the bridge: the sum of every PreToolUse hook timeout settings.json registers, since the
    bridge runs the matching ones in sequence and agy must not cut it before the slowest chain decides."""
    try:
        settings = json.load(open(os.path.join(root, ".claude", "settings.json"), encoding="utf-8"))
    except (OSError, ValueError):
        return DEFAULT_HOOK_TIMEOUT
    return sum(h.get("timeout") or DEFAULT_HOOK_TIMEOUT
               for group in settings.get("hooks", {}).get("PreToolUse", []) for h in group.get("hooks", []))


def hooks(root):
    """Only PreToolUse: the bridge acts on it alone and answers {} to every other event, so registering one would
    spawn a bridge per agy call for nothing."""
    bridge = os.path.join(root, ".claude", "hooks", "agy_hook_bridge.py").replace("\\", "/")
    return {"hooks.json": json.dumps({
        "project-guards": {"PreToolUse": [{"matcher": "*", "hooks": [{"command": f'python3 "{bridge}" PreToolUse',
                                                                      "timeout": _bridge_timeout(root)}]}]},
    }, indent=2) + "\n"}


def _semantic_search():
    """The semantic-search plugin's newest installed launch line, or None when the plugin is absent."""
    base = os.path.join(os.path.expanduser("~"), ".claude", "plugins", "cache", "dreb", "semantic-search")
    versions = [v for v in os.listdir(base) if re.fullmatch(r"\d+(\.\d+)*", v)] if os.path.isdir(base) else []
    for version in sorted(versions, key=lambda v: [int(x) for x in v.split(".")], reverse=True):
        plugin = os.path.join(base, version)
        try:
            server = json.load(open(os.path.join(plugin, ".mcp.json"), encoding="utf-8"))["mcpServers"]["semantic-search"]
        except (OSError, ValueError, KeyError):
            continue
        sub = lambda s: s.replace("${CLAUDE_PLUGIN_ROOT}", plugin.replace("\\", "/"))
        return {"command": server["command"], "args": [sub(a) for a in server.get("args", [])]}
    return None


def mcp(root):
    """Read-only servers only: semantic search and the project's read-only git server. A server that edits the
    project (godot) stays out."""
    servers = {}
    search = _semantic_search() if "semantic-search" in READ_ONLY_SERVERS else None
    if search:
        servers["semantic-search"] = search
    try:
        project = json.load(open(os.path.join(root, ".mcp.json"), encoding="utf-8")).get("mcpServers", {})
    except (OSError, ValueError):
        project = {}
    native = root.replace("\\", "/")
    sub = lambda s: re.sub(r"\$\{CLAUDE_PROJECT_DIR(:-[^}]*)?\}", native, s)
    for name in READ_ONLY_SERVERS:
        if name in project:
            entry = project[name]
            servers[name] = {"command": entry["command"], "args": [sub(a) for a in entry.get("args", [])],
                             "env": {k: sub(v) for k, v in entry.get("env", {}).items()}}
    return {"mcp_config.json": json.dumps({"mcpServers": servers}, indent=2) + "\n"}


def plan(root):
    files = {}
    for part in (rules(root), skills(root), hooks(root), mcp(root)):
        files.update(part)
    return files


def write(root):
    """Write the plan under <root>/.agents, touching only changed files, and remove generated files the plan no
    longer names. Returns the count written."""
    target = os.path.join(root, ".agents")
    files = plan(root)
    written = 0
    for rel, content in files.items():
        path = os.path.join(target, rel)
        try:
            if open(path, encoding="utf-8").read() == content:
                continue
        except OSError:
            pass
        os.makedirs(os.path.dirname(path), exist_ok=True)
        # Two jobs can share a run root, and one's agy may read a file the other rewrites: write aside, then rename.
        staged = f"{path}.{os.getpid()}.tmp"
        with open(staged, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
        replace_path(staged, path)
        written += 1
    wanted = {os.path.normcase(os.path.join(target, rel)) for rel in files}
    for stale in glob.glob(os.path.join(target, "rules", "*.md")) + glob.glob(os.path.join(target, "skills", "*", "SKILL.md")):
        if os.path.normcase(stale) in wanted:
            continue
        try:
            if MARK in open(stale, encoding="utf-8").read():
                os.remove(stale)
                if stale.endswith("SKILL.md") and not os.listdir(os.path.dirname(stale)):
                    os.rmdir(os.path.dirname(stale))
        except OSError:
            pass
    return written


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    w = sub.add_parser("write")
    w.add_argument("--root", required=True)
    args = ap.parse_args(argv)
    root = os.path.abspath(args.root)
    if not os.path.isfile(os.path.join(root, ".claude", "CLAUDE.core.md")):
        print("skipped: not a checkout of this project")
        return 0
    print(f"wrote {write(root)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
