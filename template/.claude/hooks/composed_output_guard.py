#!/usr/bin/env python3
"""Hook: PreToolUse Write|Edit, run by pre_edit_dispatch.py — block a direct edit of composed or generated text.

`baseline_sync.py compose` regenerates each composed file from its inputs, so a direct edit is
silently dropped by the next compose. The block
names the inputs to edit instead. The composed set has one home: `WATCH_COMPOSED_INPUTS` in
`.claude/tools/baseline_sync.py`. The `settings.json` block also names each shipped
`settings.<layer>.json` overlay (`_hook_state.SETTINGS_FILES`), since compose merges those too.

A generated REGION — the lines from `GENERATED by <tool> from <source> - do not edit` to
`END GENERATED by <tool>` in any file — is the same class: its generator overwrites the region, or
refuses to run over a hand edit. An Edit whose old text overlaps a region or its markers,
or a Write that changes one, is blocked with the source to edit and the generator to run; the
generator is found by walking up from the file.

Contract: `process(payload)` returns {"block": message} or None (pre_edit_dispatch.py).
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from _claude_scope import harness_tail  # noqa: E402
from _hook_state import SETTINGS_FILES  # noqa: E402

_TOOLS = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "tools")


# Basenames of the composed files, checked before importing baseline_sync on every edit. A proof
# pins this set to WATCH_COMPOSED_INPUTS, so the composed set keeps one home.
COMPOSED_NAMES = {"settings.json", "memory_domains.md"}


def _composed_inputs():
    sys.path.insert(0, _TOOLS)
    from baseline_sync import WATCH_COMPOSED_INPUTS
    return {rel[len(".claude/"):]: inputs for rel, inputs in WATCH_COMPOSED_INPUTS.items()}


REGION = re.compile(r"^(?:#|//) GENERATED by (\S+) from (.+?) - do not edit\..*?$(.*?)^(?:#|//) END GENERATED by \1",
                    re.M | re.S)


def _regions(text):
    return [(m.start(), m.end(), m.group(1), m.group(2), m.group(0)) for m in REGION.finditer(text or "")]


def _generator(path, tool):
    d = os.path.dirname(os.path.abspath(path))
    while True:
        if os.path.isfile(os.path.join(d, tool)):
            return d
        up = os.path.dirname(d)
        if up == d:
            return None
        d = up


def _generated_block(payload):
    ti = payload.get("tool_input") or {}
    path = ti.get("file_path") or ""
    try:
        with open(path, encoding="utf-8", errors="replace") as fh:
            text = fh.read()
    except OSError:
        return None
    if "GENERATED by " not in text:
        return None
    hit = None
    if payload.get("tool_name") == "Edit":
        old = ti.get("old_string") or ""
        spans = [(m.start(), m.end()) for m in re.finditer(re.escape(old), text)] if old else []
        hit = next((r for r in _regions(text) for a, b in spans if a < r[1] and b > r[0]), None)
    else:
        new = {(r[2], r[3]): r[4] for r in _regions(ti.get("content") or "")}
        hit = next((r for r in _regions(text) if new.get((r[2], r[3])) != r[4]), None)
    if not hit:
        return None
    tool, source = hit[2], hit[3]
    home = _generator(path, tool)
    where = home.replace("\\", "/") if home else "the generator's directory"
    return {"block": "BLOCKED: %s holds a region generated by %s from %s (its `do not edit` marker); the generator "
                     "overwrites or refuses a hand edit there. Edit %s (relative to %s), then run `python3 %s/%s`."
                     % (os.path.basename(path), tool, source, source, where, where, tool)}


def _in_user_claude(path):
    """The user-level ~/.claude holds the user's own settings; compose never writes it."""
    def norm(p):
        return os.path.normcase(os.path.abspath(p)).replace("\\", "/").rstrip("/") + "/"
    return norm(path).startswith(norm(os.path.expanduser("~/.claude")))


def process(payload):
    if payload.get("tool_name") not in ("Write", "Edit"):
        return None
    path = (payload.get("tool_input") or {}).get("file_path") or ""
    generated = _generated_block(payload)
    if generated:
        return generated
    if _in_user_claude(path):
        return None
    tail = harness_tail(path.replace("\\", "/"))
    if not tail or os.path.basename(tail) not in COMPOSED_NAMES:
        return None
    inputs = _composed_inputs().get(tail)
    if not inputs:
        return None
    if tail == "settings.json":
        shipped = [f[len(".claude/"):] for f in SETTINGS_FILES]
        overlays = [n for n in shipped if n != tail and n not in inputs]
        inputs = [inputs[0], *overlays, *inputs[1:]]
    home = ("rules/harness_tooling.md" if tail == "settings.json"
            else "reference/memory_domains.base.md header")
    return {"block": "BLOCKED: .claude/%s (%s) is composed; `compose` overwrites a direct edit. Edit %s "
                     "(a project override goes in the local input; `$disable` removes a base entry), then "
                     "run `python3 .claude/tools/baseline_sync.py compose`." % (tail, home, " or ".join(inputs))}


if __name__ == "__main__":
    try:
        result = process(json.load(sys.stdin))
    except (ValueError, OSError):
        sys.exit(0)
    if result:
        sys.stderr.write(result["block"] + "\n")
        sys.exit(2)
    sys.exit(0)
